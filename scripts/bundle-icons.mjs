// Bundles every Iconify icon the app references so icons render on first paint (and during SSR)
// instead of being fetched from api.iconify.design at runtime. `bun run icons` rewrites the bundle; the
// build runs it first and `bun run lint` runs it with --check, so the bundle cannot drift from the source.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { getIcons } from "@iconify/utils";

const require = createRequire(import.meta.url);
const ROOT = fileURLToPath(new URL("..", import.meta.url));
const CHECK = process.argv.includes("--check");
const SCAN = ["app", "components", "lib"];
const SETS = { lucide: "@iconify-json/lucide/icons.json", "simple-icons": "@iconify-json/simple-icons/icons.json" };

function* files(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (name === "generated-icons.ts" || name === "ui") continue;
    if (statSync(p).isDirectory()) yield* files(p);
    else if (/\.(tsx?|mjs)$/.test(name)) yield p;
  }
}

const used = new Map(Object.keys(SETS).map((k) => [k, new Set()]));
for (const dir of SCAN) {
  for (const f of files(join(ROOT, dir))) {
    for (const m of readFileSync(f, "utf8").matchAll(/["'`](lucide|simple-icons):([a-z0-9-]+)["'`]/g)) used.get(m[1]).add(m[2]);
  }
}

const out = [];
let missing = [];
for (const [prefix, pkg] of Object.entries(SETS)) {
  const names = [...used.get(prefix)].sort();
  if (!names.length) continue;
  const subset = getIcons(require(pkg), names);
  if (!subset) throw new Error(`no icons found for ${prefix}`);
  missing.push(...names.filter((n) => !(n in subset.icons) && !(subset.aliases && n in subset.aliases)).map((n) => `${prefix}:${n}`));
  delete subset.not_found;
  out.push(subset);
}
if (missing.length) {
  console.error(`Unknown icons: ${missing.join(", ")}`);
  process.exit(1);
}
const total = out.reduce((n, s) => n + Object.keys(s.icons).length + Object.keys(s.aliases ?? {}).length, 0);
const target = join(ROOT, "components/generated-icons.ts");
const content = `// Generated by scripts/bundle-icons.mjs — do not edit. ${total} icons.\nimport type { IconifyJSON } from "@iconify/react";\n\nexport const ICON_SETS: IconifyJSON[] = ${JSON.stringify(out)};\n`;
if (CHECK) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== content) {
    console.error("components/generated-icons.ts is out of date: run `bun run icons`.");
    process.exit(1);
  }
  console.log(`icon bundle up to date (${total} icons)`);
} else {
  writeFileSync(target, content);
  console.log(`bundled ${total} icons`);
}
